/** Look of a stage: sky colors, floor tile colors, and which scenery is drawn behind the board. */
enum class Theme(val skyTop: Int, val skyBottom: Int, val tileA: Int, val tileB: Int) {
    FOREST(0xFF9ED8A0.toInt(), 0xFFDDF2C8.toInt(), 0xBB5FA35E.toInt(), 0xBB4E8E4E.toInt()),
    CAVE(0xFF2E2A33.toInt(), 0xFF6B6160.toInt(), 0xBB8A8078.toInt(), 0xBB746A62.toInt()),
    PLAIN(0xFF6EB8FF.toInt(), 0xFFD9F0FF.toInt(), 0xBB9CCB6A.toInt(), 0xBB8BBB5A.toInt()),
    FACTORY(0xFF4A4F5C.toInt(), 0xFF9AA0AD.toInt(), 0xBB6E7480.toInt(), 0xBB60656F.toInt()),
    TOWER(0xFF1E1438.toInt(), 0xFF6A4E8E.toInt(), 0xBB5A4A78.toInt(), 0xBB4E4068.toInt()),
    SEA(0xFF7FCBFF.toInt(), 0xFF1E6FB8.toInt(), 0xBB3F9FD8.toInt(), 0xBB3288C4.toInt()),
    VOLCANO(0xFF3A0E0E.toInt(), 0xFFE0622B.toInt(), 0xBB6B3A2A.toInt(), 0xBB5E3224.toInt()),
    MOUNTAIN(0xFF2D3A55.toInt(), 0xFF8EA0B8.toInt(), 0xBB7A8A6A.toInt(), 0xBB6E7E5E.toInt()),
    PLATEAU(0xFF3C78C8.toInt(), 0xFFBFE4FF.toInt(), 0xBB86C36B.toInt(), 0xBB79B65E.toInt()),
}

class LevelDef(
    val id: Int,
    val name: String,
    /** Enemy types that can spawn in this level. */
    val pool: List<EnemyType>,
    /** Total enemies in the level, including the boss if there is one. */
    val count: Int,
    /** Average seconds between spawns. */
    val interval: Float,
    val startSun: Int,
    /** When true, the last enemy spawned is Gengar. */
    val bossAtEnd: Boolean,
    val theme: Theme,
    /** Pokemon recruited the first time this stage is cleared. */
    val recruits: List<DefenderType>,
)

